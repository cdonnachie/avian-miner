#!/bin/sh
# Turn webui/index.html into a C header holding it as one string literal.
#
#   webui/mkpage.sh webui/avian-webui-page.h
#
# Embedded rather than read from disk beside the binary, for the reason
# cuda/ocl/mkkernels.sh embeds the kernels: a program that loads its own page
# from a file is one missing file away from serving nothing, and that file
# would then have to be packaged, found, and kept in step with the binary
# answering for it. Embedded, avian-webui is a single file that either runs or
# is not there.
#
# POSIX sh and sed only. This runs during a build and must not need python or
# perl installed, which is the whole reason the C version of the dashboard
# exists.
set -eu

src=$(cd "$(dirname "$0")" && pwd)/index.html
out=${1:?usage: mkpage.sh OUTPUT.h}

[ -f "$src" ] || { echo "mkpage.sh: no $src" >&2; exit 1; }

# A line at a time, so the generated header stays diffable and a compiler
# error in it points somewhere. Adjacent string literals concatenate, so the
# result is still one array.
#
# Backslashes first: escaping them after the quotes would escape the
# backslashes this very step had just added.
#
# tr strips CR, because a checkout on Windows has CRLF line endings and those
# would otherwise be baked into every line of the served page.
{
	echo '/* Generated by webui/mkpage.sh from webui/index.html. Do not edit. */'
	echo '#ifndef AVIAN_WEBUI_PAGE_H'
	echo '#define AVIAN_WEBUI_PAGE_H 1'
	echo ''
	echo 'static const char avian_webui_page[] ='
	tr -d '\015' < "$src" | sed \
		-e 's/\\/\\\\/g' \
		-e 's/"/\\"/g' \
		-e 's/^/"/' \
		-e 's/$/\\n"/'
	echo ';'
	echo ''
	echo '#endif /* AVIAN_WEBUI_PAGE_H */'
} > "$out.tmp"
mv -f "$out.tmp" "$out"
