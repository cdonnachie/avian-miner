#!/bin/sh
# Write the commit this build came from into a header, for the startup banner.
#
#   mkversion.sh OUT SRCDIR
#
# Rewritten only when the value changes, so a new commit recompiles the one
# file that includes it and an unchanged tree recompiles nothing. That is what
# makes it safe for make to run this on every build, which is the point: a
# hash settled at configure time goes stale the moment you commit and run make
# again, which is exactly when a wrong answer would mislead.
#
# --no-optional-locks because git cannot write .git/index.lock on an NTFS
# volume mounted in WSL. It fails with "Bad file descriptor" and then reports
# a clean tree as dirty, which would mark every build from such a checkout.
set -e

out=$1
src=$2
q='"'
rev=

if [ -d "$src/.git" ] && command -v git >/dev/null 2>&1 ; then
    rev=$(git -C "$src" --no-optional-locks rev-parse --short=9 HEAD 2>/dev/null || true)
    if [ -n "$rev" ] ; then
        # autogen.sh rewrites these tracked files on every build and they are
        # stale in the repo by design, so counting them would put -dirty on
        # every build from a pristine commit and leave the suffix meaning
        # nothing. Measured: without this the container, which clones a clean
        # tree and then runs autogen, called itself dirty.
        gen=':(exclude)configure :(exclude)aclocal.m4'
        gen="$gen :(exclude)*Makefile.in :(exclude)cpuminer-config.h.in"
        dirt=$(git -C "$src" --no-optional-locks status --porcelain --untracked-files=no -- $gen 2>/dev/null || true)
        [ -z "$dirt" ] || rev="$rev-dirty"
    fi
fi

{
    echo "/* Generated by make. Do not edit, do not commit. */"
    echo "/* The commit this was built from, empty when there is no checkout"
    echo "   to ask, as in a build from a release tarball. */"
    echo "#define AVIAN_GIT_REV $q$rev$q"
} > "$out.tmp"

if cmp -s "$out.tmp" "$out" 2>/dev/null ; then
    rm -f "$out.tmp"
else
    mv -f "$out.tmp" "$out"
fi
