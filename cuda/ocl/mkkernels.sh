#!/bin/sh
# Turn cuda/ocl/kernels/x16-*.cl into a C header of string literals.
#
#   cuda/ocl/mkkernels.sh cuda/ocl/avian-ocl-kernels.h
#
# The kernels are embedded rather than read from disk at run time, for the
# same reason the CUDA backend carries its fatbinary: a backend that loads its
# kernels from files beside it is one missing file away from a card that
# silently does nothing, and those files would then have to be packaged,
# found and version-matched. Embedded, the library is self-contained.
#
# Each #include is resolved here, because clBuildProgram cannot: there is no
# include path once the source is a string in memory. Include depth is one by
# design, so this needs no recursion; a kernel source whose include itself
# includes something would silently lose the inner file, so that is refused
# here rather than miscompiled later.
#
# POSIX sh, sed and awk only. This runs during a build and must not need
# python or perl installed.
set -eu

K=$(cd "$(dirname "$0")" && pwd)/kernels
out=${1:?usage: mkkernels.sh OUTPUT.h}

# sed rather than awk for the escaping. A backslash in an awk gsub
# replacement is a well-known trap, and these sources are full of macro
# continuations, so there are plenty of them to get wrong.
escape() {
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/"/' -e 's/$/\\n"/'
}

inline() {
    awk -v dir="$K" '
        /^#include "/ {
            f = $0
            sub(/^#include "/, "", f)
            sub(/".*$/, "", f)
            path = dir "/" f
            while ((getline line < path) > 0) {
                if (line ~ /^#include "/) {
                    print "mkkernels.sh: " f " includes a file; depth is one by design" > "/dev/stderr"
                    exit 1
                }
                print line
            }
            close(path)
            next
        }
        { print }
    ' "$1"
}

{
    cat <<'HEAD'
/* Generated by cuda/ocl/mkkernels.sh from cuda/ocl/kernels/x16-*.cl.
 * Do not edit: edit the .cl files and rebuild.
 *
 * The sources carry their own licences. The round functions are MIT, from
 * Projet RNRT SAPHIR's sphlib by way of sgminer; the notices are inline. */

#ifndef AVIAN_OCL_KERNELS_H
#define AVIAN_OCL_KERNELS_H 1

HEAD

    entries=""
    for f in "$K"/x16-*.cl ; do
        base=$(basename "$f" .cl)
        sym=$(printf '%s' "$base" | tr '-' '_')
        entry=$(sed -n 's/^[ 	*]*avian-ocl-entry:[ 	]*\([A-Za-z0-9_]*\).*/\1/p' "$f" | head -1)
        if [ -z "$entry" ] ; then
            echo "mkkernels.sh: $base.cl has no 'avian-ocl-entry:' marker" >&2
            exit 1
        fi
        printf '/* %s.cl, entry point %s */\n' "$base" "$entry"
        printf 'static const char k_%s[] =\n' "$sym"
        inline "$f" | escape
        printf ';\n\n'
        entries="$entries    { \"$entry\", k_$sym },
"
    done

    cat <<'MID'
struct avian_ocl_kernel
{
    const char *entry;      /* the __kernel name clCreateKernel wants */
    const char *source;     /* one self-contained translation unit */
};

static const struct avian_ocl_kernel avian_ocl_kernels[] = {
MID
    printf '%s' "$entries"
    cat <<'FOOT'
};

#define AVIAN_OCL_KERNEL_COUNT \
    (sizeof avian_ocl_kernels / sizeof avian_ocl_kernels[0])

#endif /* AVIAN_OCL_KERNELS_H */
FOOT
} > "$out.tmp"
mv -f "$out.tmp" "$out"
